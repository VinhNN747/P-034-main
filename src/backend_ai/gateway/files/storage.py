"""Where uploaded file bytes live. Metadata (owner, expiry...) is in the
``gateway_files`` table; a backend only maps an opaque key to bytes."""

from __future__ import annotations

import asyncio
from collections.abc import AsyncIterator
from pathlib import Path
from typing import Protocol


class FileStorageError(RuntimeError):
    pass


class FileStorageNotFound(FileStorageError):  # noqa: N818 - public interface in approved plan
    pass


class FileStorageUnavailable(FileStorageError):  # noqa: N818 - public interface in approved plan
    pass


class FileStoragePermissionError(FileStorageError):
    pass


def _storage_error(exc):
    code = getattr(exc, "response", {}).get("Error", {}).get("Code")
    if isinstance(exc, FileNotFoundError) or code in {"NoSuchKey", "NotFound", "404"}:
        return FileStorageNotFound("Stored object is missing")
    if isinstance(exc, PermissionError) or code in {"AccessDenied", "403", "InvalidAccessKeyId", "SignatureDoesNotMatch"}:
        return FileStoragePermissionError("Storage permission denied")
    return FileStorageUnavailable("Storage is temporarily unavailable")


async def _storage_call(function, *args, _close_on_cancel=False, **kwargs):
    # Threads cannot be cancelled. Do not let compensation race a late write
    # or close a handle while a thread still reads it.
    task = asyncio.create_task(asyncio.to_thread(function, *args, **kwargs))
    try:
        return await asyncio.shield(task)
    except asyncio.CancelledError:
        import anyio
        with anyio.CancelScope(shield=True):
            try:
                result = await task
                if _close_on_cancel:
                    handle = result.get('Body') if isinstance(result, dict) else result
                    if handle is not None:
                        await asyncio.to_thread(handle.close)
            except Exception:
                pass
        raise
    except Exception as exc:
        raise _storage_error(exc) from exc


class FileStorage(Protocol):
    name: str

    async def put(self, key: str, data: bytes, *, content_type: str) -> None: ...

    async def get(self, key: str) -> bytes: ...

    async def delete(self, key: str) -> None: ...

    def iter_content(self, key: str, chunk_bytes: int = 65536) -> AsyncIterator[bytes]: ...


class LocalFileStorage:
    """Files under a root directory; for development and single-node
    deployments. Keys are generated by the service, never by callers."""

    name = "local"

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if self.root not in path.parents:
            raise FileStorageError("storage key escapes the storage root")
        return path

    async def put(self, key: str, data: bytes, *, content_type: str) -> None:
        path = self._path(key)

        def write() -> None:
            path.parent.mkdir(parents=True, exist_ok=True)
            temporary = path.with_suffix(path.suffix + ".part")
            temporary.write_bytes(data)
            temporary.replace(path)

        await _storage_call(write)

    async def get(self, key: str) -> bytes:
        path = self._path(key)
        try:
            return await _storage_call(path.read_bytes)
        except FileNotFoundError as exc:
            raise FileStorageNotFound("Stored object is missing") from exc

    async def iter_content(self, key: str, chunk_bytes: int = 65536):
        try:
            handle = await _storage_call(self._path(key).open, 'rb', _close_on_cancel=True)
        except FileNotFoundError as exc:
            raise FileStorageNotFound('Stored object is missing') from exc
        except OSError as exc:
            raise FileStorageUnavailable('Storage read failed') from exc
        try:
            while chunk := await _storage_call(handle.read, chunk_bytes):
                yield chunk
        finally:
            await _storage_call(handle.close)


    async def delete(self, key: str) -> None:
        path = self._path(key)
        await _storage_call(path.unlink, missing_ok=True)
        await _storage_call(path.with_suffix(path.suffix + '.part').unlink, missing_ok=True)


class S3FileStorage:
    """Any S3-compatible store (AWS S3, MinIO, R2...). boto3 is synchronous,
    so calls run in a worker thread to keep the event loop free."""

    name = "s3"

    def __init__(
        self,
        bucket: str,
        *,
        prefix: str = "",
        region: str | None = None,
        endpoint_url: str | None = None,
        access_key_id: str | None = None,
        secret_access_key: str | None = None,
        client: object | None = None,
    ) -> None:
        if not bucket:
            raise FileStorageError("S3 storage requires a bucket name")
        self.bucket = bucket
        self.prefix = prefix.strip("/")
        if client is None:
            import boto3
            from botocore.config import Config

            client = boto3.client(
                "s3",
                region_name=region or None,
                endpoint_url=endpoint_url or None,
                # None falls back to boto3's normal credential chain (env,
                # instance role...), so keys are optional here.
                aws_access_key_id=access_key_id or None,
                aws_secret_access_key=secret_access_key or None,
                config=Config(connect_timeout=5, read_timeout=10, retries={'mode':'standard','total_max_attempts':2}),
            )
        self._client = client

    def _key(self, key: str) -> str:
        return f"{self.prefix}/{key}" if self.prefix else key

    async def put(self, key: str, data: bytes, *, content_type: str) -> None:
        await _storage_call(
            self._client.put_object, Bucket=self.bucket, Key=self._key(key), Body=data, ContentType=content_type
        )

    async def get(self, key: str) -> bytes:
        try:
            response = await _storage_call(self._client.get_object, Bucket=self.bucket, Key=self._key(key), _close_on_cancel=True)
        except FileStorageError:
            raise
        except Exception as exc:  # botocore ClientError (NoSuchKey) and transport errors
            code = getattr(exc, "response", {}).get("Error", {}).get("Code")
            if isinstance(exc, FileNotFoundError) or code in ("NoSuchKey", "NotFound", "404"):
                raise FileStorageNotFound("Stored object is missing") from exc
            if code in ("AccessDenied", "403"):
                raise FileStoragePermissionError("Storage permission denied") from exc
            raise FileStorageUnavailable("Storage is temporarily unavailable") from exc
        handle = response["Body"]
        try:
            return await _storage_call(handle.read)
        finally:
            await _storage_call(handle.close)

    async def iter_content(self, key: str, chunk_bytes: int = 65536):
        try:
            response = await _storage_call(self._client.get_object, Bucket=self.bucket, Key=self._key(key), _close_on_cancel=True)
        except FileStorageError:
            raise
        except Exception as exc:
            code = getattr(exc, 'response', {}).get('Error', {}).get('Code')
            if code in ('NoSuchKey', 'NotFound', '404'):
                raise FileStorageNotFound('Stored object is missing') from exc
            raise FileStorageUnavailable('Storage read failed') from exc
        handle = response['Body']
        try:
            while chunk := await _storage_call(handle.read, chunk_bytes):
                yield chunk
        finally:
            await _storage_call(handle.close)


    async def delete(self, key: str) -> None:
        await _storage_call(self._client.delete_object, Bucket=self.bucket, Key=self._key(key))
