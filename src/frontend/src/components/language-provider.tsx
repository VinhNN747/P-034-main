type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (key: TranslationKey, params?: TranslationParams) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

const fallbackLanguage: LanguageContextValue = {
  language: "vi",
  setLanguage: () => undefined,
  toggleLanguage: () => undefined,
  t: (key, params) => interpolate(translations.vi[key] ?? key, params),
};

function repairEncoding(value: string) {
  if (!/[\u00c3\u00c2\u00e2\u00e1\u00ba]/.test(value)) return value;
  try {
    const windows1252Bytes: Record<number, number> = {
      0x20ac: 0x80, 0x201a: 0x82, 0x192: 0x83, 0x201e: 0x84, 0x2026: 0x85, 0x2020: 0x86,
      0x2021: 0x87, 0x2c6: 0x88, 0x2030: 0x89, 0x160: 0x8a, 0x2039: 0x8b, 0x152: 0x8c,
      0x17d: 0x8e, 0x2018: 0x91, 0x2019: 0x92, 0x201c: 0x93, 0x201d: 0x94, 0x2022: 0x95,
      0x2013: 0x96, 0x2014: 0x97, 0x2dc: 0x98, 0x2122: 0x99, 0x161: 0x9a, 0x203a: 0x9b,
      0x153: 0x9c, 0x17e: 0x9e, 0x178: 0x9f,
    };
    const bytes = Uint8Array.from(value, (character) => {
      const code = character.charCodeAt(0);
      return code <= 0xff ? code : windows1252Bytes[code] ?? 0;
    });
    const repaired = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
    return repaired;
  } catch {
    return value;
  }
}

function interpolate(value: string, params?: TranslationParams) {
  value = repairEncoding(value);
  if (!params) return value;
  return Object.entries(params).reduce((result, [key, replacement]) => result.replaceAll(`{${key}}`, String(replacement)), value);
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  // Keep the server render and the first client render identical. The saved
  // preference is restored after mount so it cannot cause a hydration mismatch.
  const [language, setLanguageState] = useState<Language>("vi");

  useEffect(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === "en") {
      // eslint-disable-next-line react-hooks/set-state-in-effect
      setLanguageState("en");
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    window.localStorage.setItem(STORAGE_KEY, language);
  }, [language]);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage: (next) => setLanguageState(next),
    toggleLanguage: () => setLanguageState((current) => current === "vi" ? "en" : "vi"),
    t: (key, params) => interpolate(translations[language][key] ?? translations.en[key] ?? key, params),
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  return context ?? fallbackLanguage;
}

